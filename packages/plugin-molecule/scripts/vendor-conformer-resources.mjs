// Copies the part of OpenChemLib's static resources that conformer generation needs into
// src/generated/, as a module the browser build can lazy-load.
//
// OpenChemLib ships them as dist/resources.json (1.3 MB, BSD-3-Clause), but its package exports
// map does not expose that file, and `Resources.registerFromUrl()` would fetch it at runtime —
// something this plugin promises never to do. So the torsion and bond-length tables (the
// `/resources/cod/` entries, ~750 KB) and the MMFF94 force-field tables that relax the result
// (~190 KB) are vendored at build time from the pinned dependency and loaded only when a SMILES
// structure is drawn in 3D. The other tables (toxicity, drug-likeness) are left out.
import { createRequire } from "node:module"
import { mkdirSync, readFileSync, writeFileSync } from "node:fs"
import { dirname, join } from "node:path"
import { fileURLToPath } from "node:url"

const here = dirname(fileURLToPath(import.meta.url))
const root = join(here, "..")
const require = createRequire(join(root, "package.json"))
// The exports map hides everything but the entry point, so both files are found relative to it.
const dist = dirname(require.resolve("openchemlib"))
const source = join(dist, "resources.json")
const version = JSON.parse(readFileSync(join(dist, "..", "package.json"), "utf8")).version

const all = JSON.parse(readFileSync(source, "utf8"))
// The COD tables build the conformer; the MMFF94 tables relax it.
const WANTED = ["/resources/cod/", "/resources/forcefield/mmff94/"]
const subset = Object.fromEntries(Object.entries(all).filter(([key]) => WANTED.some((prefix) => key.startsWith(prefix))))
for (const prefix of WANTED) {
  if (!Object.keys(subset).some((key) => key.startsWith(prefix))) throw new Error(`no ${prefix} entries in ${source}`)
}

const out = join(root, "src", "generated")
mkdirSync(out, { recursive: true })
writeFileSync(
  join(out, "conformer-resources.ts"),
  [
    `// Generated by scripts/vendor-conformer-resources.mjs from openchemlib@${version} — do not edit.`,
    "// OpenChemLib is BSD-3-Clause, Copyright (c) Actelion Pharmaceuticals Ltd. / Idorsia Pharmaceuticals Ltd.",
    "// eslint-disable-next-line",
    `const resources: Record<string, string> = ${JSON.stringify(subset)}`,
    "export default resources",
    "",
  ].join("\n"),
)
console.log(`vendored ${Object.keys(subset).length} conformer resources from openchemlib@${version}`)
